// Helper to group presets by category for optgroup rendering
export const groupByCategory = (presets) => {
  return presets.reduce((acc, preset) => {
    const cat = preset.category || 'Outros';
    if (!acc[cat]) {
      acc[cat] = [];
    }
    acc[cat].push(preset);
    return acc;
  }, {});
};

